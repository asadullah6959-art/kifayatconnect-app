import { PaymentTransaction, RegionalStats, User } from '../types';

/**
 * Escapes CSV field value to comply with RFC 4180
 */
function escapeCSVField(value: any): string {
  if (value === null || value === undefined) return '""';
  const str = String(value);
  if (str.includes(',') || str.includes('"') || str.includes('\n') || str.includes('\r')) {
    return `"${str.replace(/"/g, '""')}"`;
  }
  return `"${str}"`;
}

/**
 * Triggers a direct browser file download for text/csv data with UTF-8 BOM
 */
function downloadCSV(csvContent: string, filename: string): void {
  // UTF-8 BOM ensures Excel and Google Sheets correctly display non-ASCII characters & symbols
  const blob = new Blob(['\uFEFF' + csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.setAttribute('download', filename);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

/**
 * Exports financial transactions ledger to branded CSV
 */
export function exportTransactionsToCSV(
  transactions: PaymentTransaction[],
  currentUser: User,
  filterDescription?: string
): void {
  const currentDate = new Date().toISOString().split('T')[0];
  const currentTime = new Date().toLocaleTimeString();

  const lines: string[] = [];

  // Organization Branded Header
  lines.push('KIFAYAT CONNECT WELFARE TRUST PAKISTAN');
  lines.push('Official Audited Financial Transaction Ledger & Receipts Report');
  lines.push(`Generated On,${escapeCSVField(`${currentDate} ${currentTime}`)}`);
  lines.push(`Exported By,${escapeCSVField(`${currentUser.name} (${currentUser.role})`)}`);
  lines.push(`Regional Jurisdiction,${escapeCSVField(currentUser.region)}`);
  if (filterDescription) {
    lines.push(`Applied Filter,${escapeCSVField(filterDescription)}`);
  }
  lines.push('National Tax Number (NTN),8492019-3,Govt Trust Reg # ICT-8841-KC');
  lines.push(''); // Blank row separator

  // Table Column Headers
  const headers = [
    'Receipt Number',
    'Date',
    'Member Name',
    'Membership ID',
    'Region',
    'Fund Category',
    'Payment Method',
    'Reference / Slip ID',
    'Amount (PKR)',
    'Status',
    'Verified By'
  ];
  lines.push(headers.map(escapeCSVField).join(','));

  // Data Rows
  let totalAmount = 0;
  transactions.forEach(tx => {
    totalAmount += tx.amount;
    const row = [
      tx.receiptNumber,
      tx.date,
      tx.userName,
      tx.userMembershipId,
      tx.userRegion,
      tx.fundCategory,
      tx.paymentMethod,
      tx.referenceNumber,
      tx.amount,
      tx.status,
      tx.verifiedBy || 'Pending Verification'
    ];
    lines.push(row.map(escapeCSVField).join(','));
  });

  // Summary Row
  lines.push('');
  lines.push([
    'TOTALS',
    '',
    `${transactions.length} Transactions`,
    '',
    '',
    '',
    '',
    'Grand Total (PKR):',
    totalAmount,
    '',
    ''
  ].map(escapeCSVField).join(','));

  // Footer Audit Note
  lines.push('');
  lines.push('CONFIDENTIALITY NOTICE: This financial record is generated by Kifayat Connect Central Accounting Desk. Any unauthorized alteration renders the legal voucher void.');

  const filename = `kifayat_connect_ledger_${(currentUser.district || currentUser.region || 'national').toLowerCase().replace(/\s+/g, '_')}_${currentDate}.csv`;
  downloadCSV(lines.join('\r\n'), filename);
}

/**
 * Exports audited welfare report & regional quota matrix to branded CSV
 */
export function exportReportToCSV(
  regionalStats: RegionalStats[],
  totalFunds: number,
  monthlyFunds: number,
  annualFunds: number,
  currentUser: User
): void {
  const currentDate = new Date().toISOString().split('T')[0];
  const currentTime = new Date().toLocaleTimeString();

  const lines: string[] = [];

  // Branded Header
  lines.push('KIFAYAT CONNECT WELFARE ORGANIZATION');
  lines.push('Comprehensive Audited Welfare & Regional Quota Statement');
  lines.push(`Generated On,${escapeCSVField(`${currentDate} ${currentTime}`)}`);
  lines.push(`Authorizing Officer,${escapeCSVField(`${currentUser.name} (${currentUser.role})`)}`);
  lines.push(`Jurisdiction,${escapeCSVField(currentUser.district ? `${currentUser.district}, ${currentUser.stateProvince}` : (currentUser.region || 'National'))}`);
  lines.push('Legal Trust Reg #,ICT-8841-KC,Audited by Independent Chartered Accountants');
  lines.push('');

  // Executive Summary Section
  lines.push('EXECUTIVE BALANCE RECONCILIATION');
  lines.push(`Total Verified Collections,${totalFunds},PKR`);
  lines.push(`Monthly Subscription Welfare Pool,${monthlyFunds},PKR`);
  lines.push(`Annual Welfare & Healthcare Fund,${annualFunds},PKR`);
  lines.push('');

  // Regional Performance Matrix
  lines.push('REGIONAL DIVISION PERFORMANCE MATRIX');
  const headers = [
    'Administrative Region',
    'Officer In Charge',
    'Total Members',
    'Active Members',
    'Compliance Rate (%)',
    'Total Collected (PKR)',
    'Pending Approvals',
    'Pending Grievances',
    'Audit Status'
  ];
  lines.push(headers.map(escapeCSVField).join(','));

  regionalStats.forEach(stat => {
    const complianceRate = Math.round((stat.activeMembers / stat.totalMembers) * 100);
    const row = [
      stat.region,
      stat.officerInCharge,
      stat.totalMembers,
      stat.activeMembers,
      `${complianceRate}%`,
      stat.totalCollected,
      stat.pendingApprovals,
      stat.pendingComplaints,
      'Audited & Verified'
    ];
    lines.push(row.map(escapeCSVField).join(','));
  });

  lines.push('');
  lines.push('LEGAL MINUTE: Verified and certified for organizational review under Kifayat Connect bylaws.');

  const filename = `kifayat_connect_audited_statement_${currentDate}.csv`;
  downloadCSV(lines.join('\r\n'), filename);
}
